#!/bin/bash
# ============================================================
# setup-hosts.sh — Cập nhật /etc/hosts cho bank-cluster-profile
#
# Khi nào cần chạy:
#   1. Sau khi chạy 03-deploy-bank.sh (lần đầu setup)
#   2. Sau khi WSL2 restart (nếu wsl.conf chưa có generateHosts=false)
#   3. Sau khi recreate cluster (IP có thể thay đổi)
#
# Yêu cầu: sudo (để ghi /etc/hosts)
#
# Cách dùng:
#   ./setup-hosts.sh               # Tự động phát hiện IP
#   ./setup-hosts.sh --tunnel      # Ưu tiên LoadBalancer EXTERNAL-IP (cần tunnel đang chạy)
#   ./setup-hosts.sh --nodeport    # Dùng minikube node IP (không cần tunnel)
# ============================================================
set -euo pipefail

RED='\033[0;31m'; YELLOW='\033[1;33m'; GREEN='\033[0;32m'; BLUE='\033[0;34m'; NC='\033[0m'

CONTEXT="bank-cluster-profile"
PREFER_MODE="${1:-auto}"   # --tunnel | --nodeport | auto (default)

DOMAINS_LINE1="bank.openbanking.dev health.bank.openbanking.dev"
DOMAINS_LINE2="kiali.bank.openbanking.dev grafana.bank.openbanking.dev prometheus.bank.openbanking.dev tracing.bank.openbanking.dev"
MARKER="# openbanking-ecosystem"

echo "================================================================"
echo " setup-hosts.sh — Update /etc/hosts for bank-cluster-profile"
echo "================================================================"

# ── Kiểm tra quyền sudo ─────────────────────────────────────────────
if ! sudo -n true 2>/dev/null; then
  echo -e "${YELLOW}  Yêu cầu sudo password để ghi /etc/hosts:${NC}"
fi

# ── Xác định IP đúng ────────────────────────────────────────────────
echo ""
echo -e "${BLUE}Detecting IP...${NC}"

BANK_IP=""

# Thử lấy EXTERNAL-IP từ LoadBalancer service (nếu tunnel đang chạy)
if [[ "$PREFER_MODE" != "--nodeport" ]]; then
  EXTERNAL_IP=$(kubectl get svc istio-ingressgateway \
    -n istio-system \
    --context="$CONTEXT" \
    -o jsonpath='{.status.loadBalancer.ingress[0].ip}' 2>/dev/null || echo "")

  if [[ -n "$EXTERNAL_IP" && "$EXTERNAL_IP" != "<pending>" ]]; then
    BANK_IP="$EXTERNAL_IP"
    echo -e "  ${GREEN}✓ LoadBalancer EXTERNAL-IP: $BANK_IP${NC}"
    echo "    (cần 'minikube tunnel --profile $CONTEXT' đang chạy để dùng port 443)"
  fi
fi

# Fallback: dùng minikube node IP (NodePort :30443)
if [[ -z "$BANK_IP" ]]; then
  BANK_IP=$(minikube ip --profile "$CONTEXT" 2>/dev/null || echo "")
  if [[ -n "$BANK_IP" ]]; then
    echo -e "  ${YELLOW}⚠ Dùng minikube node IP: $BANK_IP (NodePort)${NC}"
    echo "    Truy cập cần thêm :30443, ví dụ: https://kiali.bank.openbanking.dev:30443/kiali/"
    echo "    Để dùng port 443 chuẩn: chạy 'minikube tunnel --profile $CONTEXT'"
    echo "    rồi chạy lại: ./setup-hosts.sh --tunnel"
  else
    echo -e "${RED}⛔ Không lấy được IP. Kiểm tra cluster đang chạy:${NC}"
    echo "  minikube status --profile $CONTEXT"
    exit 1
  fi
fi

# ── Xóa entries cũ & thêm mới vào /etc/hosts ────────────────────────
echo ""
echo -e "${BLUE}Updating /etc/hosts...${NC}"
echo "  IP    : $BANK_IP"
echo "  Domains: $DOMAINS_LINE1"
echo "           $DOMAINS_LINE2"

# Tạo block mới
NEW_BLOCK="
${MARKER} (auto-generated by setup-hosts.sh — do not edit manually)
$BANK_IP  $DOMAINS_LINE1
$BANK_IP  $DOMAINS_LINE2"

# Xóa block cũ (mọi dòng có marker hoặc dòng chứa các domain)
TEMP_FILE=$(mktemp)
grep -v "$MARKER\|bank\.openbanking\.dev\|kiali\.bank\|grafana\.bank\|prometheus\.bank\|tracing\.bank\|health\.bank" \
  /etc/hosts > "$TEMP_FILE" || true

# Thêm block mới
echo "$NEW_BLOCK" >> "$TEMP_FILE"

# Ghi vào /etc/hosts (cần sudo)
sudo cp "$TEMP_FILE" /etc/hosts
rm -f "$TEMP_FILE"

echo ""
echo -e "${GREEN}✓ /etc/hosts đã cập nhật:${NC}"
grep "openbanking" /etc/hosts

# ── Kiểm tra WSL generateHosts ──────────────────────────────────────
echo ""
echo -e "${BLUE}Checking WSL auto-regeneration...${NC}"
if grep -q "generateHosts = false" /etc/wsl.conf 2>/dev/null; then
  echo -e "  ${GREEN}✓ wsl.conf: generateHosts=false (entries được giữ sau WSL restart)${NC}"
else
  echo -e "  ${YELLOW}⚠ wsl.conf CHƯA có 'generateHosts=false'${NC}"
  echo "    Entries sẽ BỊ XÓA khi WSL restart!"
  echo ""
  echo "    Fix: Chạy lệnh sau rồi restart WSL:"
  echo "      sudo tee -a /etc/wsl.conf <<'EOF'"
  echo "      [network]"
  echo "      generateHosts = false"
  echo "      EOF"
  echo "      # Sau đó: wsl.exe --shutdown (từ PowerShell/CMD)"
  echo "      # Rồi mở lại WSL terminal và chạy lại setup-hosts.sh"
fi

# ── Cài CA của cluster vào trust store WSL ──────────────────────────
# Mục đích: để curl/wget (tiến trình Linux) TIN cert TLS của Ingress Gateway
# mà KHÔNG cần -k. Lưu ý: import CA vào Windows store KHÔNG áp cho curl trong WSL —
# curl Linux đọc /etc/ssl/certs/ca-certificates.crt, nên phải cài riêng ở đây.
# File CA = tls.crt của Secret ca-secret (ns istio-system), do cert-manager sinh.
echo ""
echo -e "${BLUE}Installing cluster CA into WSL trust store...${NC}"
CA_DST="/usr/local/share/ca-certificates/bank-cluster-ca.crt"   # phải đuôi .crt
CA_TMP=$(mktemp)
if kubectl get secret ca-secret -n istio-system --context="$CONTEXT" \
     -o jsonpath='{.data.tls\.crt}' 2>/dev/null | base64 -d > "$CA_TMP" && [[ -s "$CA_TMP" ]]; then
  CA_SUBJECT=$(openssl x509 -in "$CA_TMP" -noout -subject 2>/dev/null | sed 's/subject=//' || echo "?")
  if sudo cmp -s "$CA_TMP" "$CA_DST" 2>/dev/null; then
    echo -e "  ${GREEN}✓ CA đã có trong trust store (không đổi): $CA_SUBJECT${NC}"
  else
    sudo cp "$CA_TMP" "$CA_DST"
    sudo update-ca-certificates >/dev/null 2>&1
    echo -e "  ${GREEN}✓ Đã cài CA: $CA_SUBJECT${NC}"
    echo "    → curl/wget (Linux) giờ tin TLS *.bank.openbanking.dev mà KHÔNG cần -k"
  fi
else
  echo -e "  ${YELLOW}⚠ Chưa lấy được secret 'ca-secret' (ns istio-system) — bỏ qua bước cài CA.${NC}"
  echo "    Cluster có thể chưa deploy cert-manager issuers; chạy 03-deploy-bank.sh trước."
  echo "    Tới khi CA được cài, curl vẫn cần -k (hoặc --cacert <file>)."
fi
rm -f "$CA_TMP"

# ── Verify connectivity ──────────────────────────────────────────────
echo ""
echo -e "${BLUE}Verifying DNS resolution...${NC}"
for domain in bank.openbanking.dev kiali.bank.openbanking.dev; do
  resolved=$(getent hosts "$domain" 2>/dev/null | awk '{print $1}' || echo "FAILED")
  if [[ "$resolved" == "$BANK_IP" ]]; then
    echo -e "  ${GREEN}✓ $domain → $resolved${NC}"
  else
    echo -e "  ${RED}✗ $domain → $resolved (expected $BANK_IP)${NC}"
  fi
done

echo ""
echo "================================================================"
echo -e "${GREEN}✓ Done. Test access:${NC}"
if [[ "$BANK_IP" == "$(kubectl get svc istio-ingressgateway -n istio-system \
    --context="$CONTEXT" \
    -o jsonpath='{.status.loadBalancer.ingress[0].ip}' 2>/dev/null)" ]]; then
  echo "  curl -sk https://bank.openbanking.dev/oauth2/.well-known/openid-configuration"
  echo "  curl -o/dev/null -sk -L -w '%{http_code}\n' https://kiali.bank.openbanking.dev/kiali/"
else
  echo "  curl -sk https://bank.openbanking.dev:30443/oauth2/.well-known/openid-configuration"
  echo "  curl -o/dev/null -sk -L -w '%{http_code}\n' https://kiali.bank.openbanking.dev:30443/kiali/"
fi
echo "================================================================"
