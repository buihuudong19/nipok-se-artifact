#!/usr/bin/env bash
# =============================================================================
# generate-secrets.sh - Generates the deployment secrets of the testbed (random values, local files only).
#
# Creates the files below when they are missing (existing files are kept, so a running cluster keeps working):
#   secrets/secrets.env           variables read by up.sh and the test scripts (through secrets/load-secrets.sh)
#   secrets/helm-secrets.yaml     Helm values passed to the bank chart by 03-deploy-bank.sh and 100-redeploy-bank-cluster.sh
#   bank/kubernetes/helm/components/gateway/keystore/edge-test.p12   TLS keystore of the Spring Cloud Gateway
#   bank/spring-cloud/gateway/src/test/resources/keystore/edge-test.p12   keystore of the gateway unit test (password changeit)
# All of them are listed in .gitignore and must never be committed.
#
# Usage:  ./generate-secrets.sh            # create what is missing
#         ./generate-secrets.sh --force    # regenerate everything; then redeploy the bank cluster. A new pepper
#                                          # invalidates the stored PSU password hashes (the PSUs must be enrolled again).
# Requires: openssl, keytool (JDK).
# =============================================================================
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TESTBED="$(cd "$DIR/.." && pwd)"
ENV_FILE="$DIR/secrets.env"
HELM_FILE="$DIR/helm-secrets.yaml"
GW_KS="$TESTBED/bank/kubernetes/helm/components/gateway/keystore/edge-test.p12"
GW_TEST_KS="$TESTBED/bank/spring-cloud/gateway/src/test/resources/keystore/edge-test.p12"
FORCE=false; [ "${1:-}" = "--force" ] && FORCE=true
command -v openssl >/dev/null || { echo "ERROR: openssl is required" >&2; exit 1; }
command -v keytool >/dev/null || { echo "ERROR: keytool (JDK) is required" >&2; exit 1; }
umask 077

rnd() { openssl rand -base64 64 | tr -dc 'A-Za-z0-9' | head -c "${1:-24}"; }

if $FORCE || [ ! -s "$ENV_FILE" ]; then
  {
    echo "# Generated by secrets/generate-secrets.sh ($(date -u +%Y-%m-%dT%H:%M:%SZ)). Local only - never commit."
    echo "ONBOARDING_TOKEN=$(rnd 32)"
    echo "POSTGRES_PASSWORD=$(rnd 24)"
    echo "MYSQL_ROOT_PASSWORD=$(rnd 24)"
    echo "MYSQL_PAYMENT_PASSWORD=$(rnd 24)"
    echo "# SQL Server password policy: upper case, lower case, digit and symbol"
    echo "MSSQL_SA_PASSWORD=Sa1-$(rnd 20)"
    echo "MONGO_ROOT_PASSWORD=$(rnd 24)"
    echo "MONGO_CUSTOMER_PASSWORD=$(rnd 24)"
    echo "MONGO_PRODUCT_PASSWORD=$(rnd 24)"
    echo "GATEWAY_KEYSTORE_PASSWORD=$(rnd 24)"
    echo "PSU_PEPPER_B64=$(openssl rand -base64 32)"
  } > "$ENV_FILE"
  echo "[secrets] $ENV_FILE written" >&2
fi

# read the values without printing them
while IFS= read -r line; do
  case "$line" in ''|\#*) continue ;; esac
  printf -v "${line%%=*}" '%s' "${line#*=}"
done < "$ENV_FILE"

if $FORCE || [ ! -s "$HELM_FILE" ] || [ "$ENV_FILE" -nt "$HELM_FILE" ]; then
  cat > "$HELM_FILE" <<YAML
# Generated by secrets/generate-secrets.sh from secrets.env. Local only - never commit.
# Passed to the bank chart (environments/dev-env) with -f by 03-deploy-bank.sh and 100-redeploy-bank-cluster.sh.
mongodb:
  env:
    MONGO_INITDB_ROOT_PASSWORD: "$MONGO_ROOT_PASSWORD"
    MONGO_CUSTOMER_PASSWORD: "$MONGO_CUSTOMER_PASSWORD"
    MONGO_PRODUCT_PASSWORD: "$MONGO_PRODUCT_PASSWORD"
postgresql:
  env:
    POSTGRES_PASSWORD: "$POSTGRES_PASSWORD"
mysql:
  env:
    MYSQL_ROOT_PASSWORD: "$MYSQL_ROOT_PASSWORD"
    MYSQL_PASSWORD: "$MYSQL_PAYMENT_PASSWORD"
sqlserver:
  env:
    MSSQL_SA_PASSWORD: "$MSSQL_SA_PASSWORD"
account:
  env:
    POSTGRES_PASSWORD: "$POSTGRES_PASSWORD"
customer:
  env:
    MONGO_PASSWORD: "$MONGO_CUSTOMER_PASSWORD"
product:
  env:
    MONGO_PASSWORD: "$MONGO_PRODUCT_PASSWORD"
payment:
  env:
    MYSQL_PAYMENT_PASSWORD: "$MYSQL_PAYMENT_PASSWORD"
transaction:
  env:
    MSSQL_SA_PASSWORD: "$MSSQL_SA_PASSWORD"
gateway:
  env:
    SPRING_SSL_BUNDLE_JKS_GATEWAY_KEYSTORE_PASSWORD: "$GATEWAY_KEYSTORE_PASSWORD"
auth-server:
  env:
    SPRING_DATASOURCE_PASSWORD: "$POSTGRES_PASSWORD"
    APP_PSU_ONBOARDING_TOKEN: "$ONBOARDING_TOKEN"
YAML
  echo "[secrets] $HELM_FILE written" >&2
fi

# Self-signed TLS keystore of the gateway (alias localhost, as configured in spring.ssl.bundle.jks.gateway).
new_keystore() { # $1 = file, $2 = password (passed through the environment, not on the command line)
  mkdir -p "$(dirname "$1")"; rm -f "$1"
  KS_PASS="$2" keytool -genkeypair -alias localhost -keyalg RSA -keysize 2048 -sigalg SHA384withRSA -validity 3650 \
    -dname "CN=localhost, O=OpenBanking testbed" -ext "SAN=dns:localhost,dns:gateway" \
    -storetype PKCS12 -keystore "$1" -storepass:env KS_PASS -keypass:env KS_PASS >/dev/null 2>&1
}
if $FORCE || [ ! -s "$GW_KS" ] || [ "$ENV_FILE" -nt "$GW_KS" ]; then
  new_keystore "$GW_KS" "$GATEWAY_KEYSTORE_PASSWORD"; echo "[secrets] gateway keystore written" >&2
fi
if [ ! -s "$GW_TEST_KS" ]; then
  new_keystore "$GW_TEST_KS" changeit; echo "[secrets] gateway test keystore written" >&2
fi
