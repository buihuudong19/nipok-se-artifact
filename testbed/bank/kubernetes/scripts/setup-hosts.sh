#!/bin/bash
# ============================================================
# setup-hosts.sh - Updates /etc/hosts for bank-cluster-profile
#
# When to run it:
#   1. After 03-deploy-bank.sh (first set-up)
#   2. After a WSL2 restart (if wsl.conf does not yet contain generateHosts=false)
#   3. After re-creating the cluster (the IP may change)
#
# Requires: sudo (to write /etc/hosts)
#
# Usage:
#   ./setup-hosts.sh               # detects the IP automatically
#   ./setup-hosts.sh --tunnel      # prefers the LoadBalancer EXTERNAL-IP (needs a running tunnel)
#   ./setup-hosts.sh --nodeport    # uses the minikube node IP (no tunnel needed)
# ============================================================
set -euo pipefail

RED='\033[0;31m'; YELLOW='\033[1;33m'; GREEN='\033[0;32m'; BLUE='\033[0;34m'; NC='\033[0m'

CONTEXT="bank-cluster-profile"
PREFER_MODE="${1:-auto}"   # --tunnel | --nodeport | auto (default)

DOMAINS_LINE1="bank.openbanking.dev health.bank.openbanking.dev"
DOMAINS_LINE2="kiali.bank.openbanking.dev grafana.bank.openbanking.dev prometheus.bank.openbanking.dev tracing.bank.openbanking.dev"
MARKER="# openbanking-ecosystem"

echo "================================================================"
echo " setup-hosts.sh - Update /etc/hosts for bank-cluster-profile"
echo "================================================================"

# -- sudo check -------------------------------------------------------
if ! sudo -n true 2>/dev/null; then
  echo -e "${YELLOW}  The sudo password is needed to write /etc/hosts:${NC}"
fi

# -- Determine the right IP --------------------------------------------
echo ""
echo -e "${BLUE}Detecting IP...${NC}"

BANK_IP=""

# Try the EXTERNAL-IP of the LoadBalancer service (if the tunnel is running)
if [[ "$PREFER_MODE" != "--nodeport" ]]; then
  EXTERNAL_IP=$(kubectl get svc istio-ingressgateway \
    -n istio-system \
    --context="$CONTEXT" \
    -o jsonpath='{.status.loadBalancer.ingress[0].ip}' 2>/dev/null || echo "")

  if [[ -n "$EXTERNAL_IP" && "$EXTERNAL_IP" != "<pending>" ]]; then
    BANK_IP="$EXTERNAL_IP"
    echo -e "  ${GREEN}[ok] LoadBalancer EXTERNAL-IP: $BANK_IP${NC}"
    echo "    ('minikube tunnel --profile $CONTEXT' must be running to use port 443)"
  fi
fi

# Fallback: minikube node IP (NodePort :30443)
if [[ -z "$BANK_IP" ]]; then
  BANK_IP=$(minikube ip --profile "$CONTEXT" 2>/dev/null || echo "")
  if [[ -n "$BANK_IP" ]]; then
    echo -e "  ${YELLOW}[warn] Using the minikube node IP: $BANK_IP (NodePort)${NC}"
    echo "    Access needs :30443, e.g. https://kiali.bank.openbanking.dev:30443/kiali/"
    echo "    For the standard port 443: run 'minikube tunnel --profile $CONTEXT'"
    echo "    then run again: ./setup-hosts.sh --tunnel"
  else
    echo -e "${RED}ERROR: cannot obtain the IP. Check that the cluster is running:${NC}"
    echo "  minikube status --profile $CONTEXT"
    exit 1
  fi
fi

# -- Remove the old entries and add the new ones to /etc/hosts ---------
echo ""
echo -e "${BLUE}Updating /etc/hosts...${NC}"
echo "  IP    : $BANK_IP"
echo "  Domains: $DOMAINS_LINE1"
echo "           $DOMAINS_LINE2"

# New block
NEW_BLOCK="
${MARKER} (auto-generated by setup-hosts.sh - do not edit manually)
$BANK_IP  $DOMAINS_LINE1
$BANK_IP  $DOMAINS_LINE2"

# Remove the old block (every line with the marker or with one of the domains)
TEMP_FILE=$(mktemp)
grep -v "$MARKER\|bank\.openbanking\.dev\|kiali\.bank\|grafana\.bank\|prometheus\.bank\|tracing\.bank\|health\.bank" \
  /etc/hosts > "$TEMP_FILE" || true

# Append the new block
echo "$NEW_BLOCK" >> "$TEMP_FILE"

# Write /etc/hosts (needs sudo)
sudo cp "$TEMP_FILE" /etc/hosts
rm -f "$TEMP_FILE"

echo ""
echo -e "${GREEN}[ok] /etc/hosts updated:${NC}"
grep "openbanking" /etc/hosts

# -- WSL generateHosts check -------------------------------------------
echo ""
echo -e "${BLUE}Checking WSL auto-regeneration...${NC}"
if grep -q "generateHosts = false" /etc/wsl.conf 2>/dev/null; then
  echo -e "  ${GREEN}[ok] wsl.conf: generateHosts=false (entries are kept after a WSL restart)${NC}"
else
  echo -e "  ${YELLOW}[warn] wsl.conf does NOT contain 'generateHosts=false' yet${NC}"
  echo "    The entries will be REMOVED when WSL restarts!"
  echo ""
  echo "    Fix: run the following command, then restart WSL:"
  echo "      sudo tee -a /etc/wsl.conf <<'EOF'"
  echo "      [network]"
  echo "      generateHosts = false"
  echo "      EOF"
  echo "      # Then: wsl.exe --shutdown (from PowerShell/CMD)"
  echo "      # Then open the WSL terminal again and re-run setup-hosts.sh"
fi

# -- Install the cluster CA into the WSL trust store ------------------
# Purpose: curl/wget (Linux processes) TRUST the TLS certificate of the Ingress Gateway
# WITHOUT -k. Note: importing the CA into the Windows store does NOT apply to curl inside WSL -
# Linux curl reads /etc/ssl/certs/ca-certificates.crt, so the CA must be installed here separately.
# CA file = tls.crt of the Secret ca-secret (ns istio-system), generated by cert-manager.
echo ""
echo -e "${BLUE}Installing cluster CA into WSL trust store...${NC}"
CA_DST="/usr/local/share/ca-certificates/bank-cluster-ca.crt"   # must end in .crt
CA_TMP=$(mktemp)
if kubectl get secret ca-secret -n istio-system --context="$CONTEXT" \
     -o jsonpath='{.data.tls\.crt}' 2>/dev/null | base64 -d > "$CA_TMP" && [[ -s "$CA_TMP" ]]; then
  CA_SUBJECT=$(openssl x509 -in "$CA_TMP" -noout -subject 2>/dev/null | sed 's/subject=//' || echo "?")
  if sudo cmp -s "$CA_TMP" "$CA_DST" 2>/dev/null; then
    echo -e "  ${GREEN}[ok] CA already in the trust store (unchanged): $CA_SUBJECT${NC}"
  else
    sudo cp "$CA_TMP" "$CA_DST"
    sudo update-ca-certificates >/dev/null 2>&1
    echo -e "  ${GREEN}[ok] CA installed: $CA_SUBJECT${NC}"
    echo "    -> curl/wget (Linux) now trust TLS for *.bank.openbanking.dev WITHOUT -k"
  fi
else
  echo -e "  ${YELLOW}[warn] cannot read the secret 'ca-secret' (ns istio-system) yet - CA installation skipped.${NC}"
  echo "    The cert-manager issuers may not be deployed yet; run 03-deploy-bank.sh first."
  echo "    Until the CA is installed, curl still needs -k (or --cacert <file>)."
fi
rm -f "$CA_TMP"

# -- Verify connectivity ----------------------------------------------
echo ""
echo -e "${BLUE}Verifying DNS resolution...${NC}"
for domain in bank.openbanking.dev kiali.bank.openbanking.dev; do
  resolved=$(getent hosts "$domain" 2>/dev/null | awk '{print $1}' || echo "FAILED")
  if [[ "$resolved" == "$BANK_IP" ]]; then
    echo -e "  ${GREEN}[ok] $domain -> $resolved${NC}"
  else
    echo -e "  ${RED}[fail] $domain -> $resolved (expected $BANK_IP)${NC}"
  fi
done

echo ""
echo "================================================================"
echo -e "${GREEN}[ok] Done. Test access:${NC}"
if [[ "$BANK_IP" == "$(kubectl get svc istio-ingressgateway -n istio-system \
    --context="$CONTEXT" \
    -o jsonpath='{.status.loadBalancer.ingress[0].ip}' 2>/dev/null)" ]]; then
  echo "  curl -sk https://bank.openbanking.dev/oauth2/.well-known/openid-configuration"
  echo "  curl -o/dev/null -sk -L -w '%{http_code}\n' https://kiali.bank.openbanking.dev/kiali/"
else
  echo "  curl -sk https://bank.openbanking.dev:30443/oauth2/.well-known/openid-configuration"
  echo "  curl -o/dev/null -sk -L -w '%{http_code}\n' https://kiali.bank.openbanking.dev:30443/kiali/"
fi
echo "================================================================"
