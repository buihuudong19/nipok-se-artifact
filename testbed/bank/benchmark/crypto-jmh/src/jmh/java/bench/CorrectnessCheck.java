package bench;

import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * CORRECTNESS gate (run BEFORE the benchmark): loads THE SAME key into every available implementation, signs with
 * each implementation and cross-verifies with all the others. EdDSA is deterministic -> all signatures
 * must be EQUAL and the cross-verification must PASS (shows that all implementations follow RFC 8032 and interoperate).
 * On failure -> the benchmark figures should NOT be trusted.
 *
 * Run:  java --enable-native-access=ALL-UNNAMED -cp <jmh-jar> bench.CorrectnessCheck
 */
public final class CorrectnessCheck {

    public static void main(String[] args) {
        byte[] msg = "open-banking-ed25519-interop-check".getBytes(StandardCharsets.UTF_8);

        // Reference key generated by the baseline implementation (jca-sunec)
        KeyPairRaw kp = Providers.get("jca-sunec").generateKeyPair();

        System.out.println("== Ed25519 cross-impl interop (same key) ==");
        List<Ed25519Provider> avail = new ArrayList<>();
        for (String id : Providers.IDS) {
            Ed25519Provider p = Providers.get(id);
            if (p.available()) {
                p.useKey(kp);
                avail.add(p);
                System.out.println("  [available] " + id);
            } else {
                System.out.println("  [SKIP - unavailable] " + id);
            }
        }

        byte[] reference = null;
        boolean allOk = true;
        for (Ed25519Provider signer : avail) {
            byte[] s = signer.sign(msg);
            if (reference == null) reference = s;
            else if (!java.util.Arrays.equals(reference, s)) {
                allOk = false;
                System.out.printf("  [fail] the signature of %s DIFFERS from the reference (EdDSA must be deterministic)%n", signer.id());
            }
            for (Ed25519Provider verifier : avail) {
                if (!verifier.verify(s, msg)) {
                    allOk = false;
                    System.out.printf("  [fail] sign=%s -> verify=%s FAILED%n", signer.id(), verifier.id());
                }
            }
        }

        if (allOk) {
            System.out.println("  [ok] ALL signatures equal & cross-verification PASS - interoperability OK, benchmark valid.");
        } else {
            System.out.println("  [fail] DIFFERENCES found - fix them before benchmarking.");
            System.exit(1);
        }
    }
}
