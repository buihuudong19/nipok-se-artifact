def bold_value(cell):
    """Bold the leading value of a time cell: '$65.07 \\pm 0.37$' -> '$\\mathbf{65.07} \\pm 0.37$'."""
    m = re.fullmatch(r"\$([0-9{},.]+)( \\pm [0-9{},.]+)?\$", cell)
    if not m:
        raise ValueError(f"unexpected time cell: {cell!r}")
    return "$\\mathbf{" + m.group(1) + "}" + (m.group(2) or "") + "$"


def table11(src):
    out = []
    seen = set()
    parent = None          # generated label of the last main row
    skip_group = False
    for line in src.splitlines():
        if line.startswith("%") or not line.strip():
            continue
        s = line.strip()
        if s.startswith(r"\begin{tabular}"):
            out.append(r"\begin{tabular}{@{}lccr@{}}")
            continue
        if s.startswith(r"Operation & Side"):
            out.append(r"Operation & Side & $n$ & \textmu s \\")
            continue
        m = re.fullmatch(r"\\multicolumn\{4\}\{@\{\}l\}\{\\textit\{(.*)\}\} \\\\", s)
        if m:
            new = GROUPS11[m.group(1)]
            skip_group = new is None
            if skip_group:
                if out and out[-1] == r"\addlinespace[2pt]":
                    out.pop()       # no space before a group that is left out
            else:
                out.append(r"\multicolumn{4}{@{}l}{\textit{" + new + r"}} \\")
            continue
        m = re.fullmatch(r"\\(q?quad) (.*) \\\\", s)
        if m:
            indent = m.group(1)
            cells = [c.strip() for c in m.group(2).split("&")]
            if len(cells) != 4:
                raise ValueError(f"expected 4 cells: {line!r}")
            label, side, n, time = cells
            if indent == "qquad":
                if parent is None or parent in DROP11_SUB or ROWS11.get(parent) is None:
                    continue
                out.append(r"\qquad " + SUB11[label] + " & & & " + time + r" \\")
                continue
            if label not in ROWS11:
                raise ValueError(f"row not in ROWS11: {label!r}")
            seen.add(label)
            parent = label
            spec = ROWS11[label]
            if spec is None or skip_group:
                continue
            short, side_short, bold = spec
            cell = bold_value(time) if bold else time
            out.append(r"\quad " + short + " & " + side_short + " & " + n + " & " + cell + r" \\")
            continue
        if s in (r"\toprule", r"\midrule", r"\bottomrule", r"\addlinespace[2pt]", r"\end{tabular}"):
            out.append(s)
            continue
        raise ValueError(f"unexpected line in Table 11 body: {line!r}")
    missing = set(ROWS11) - seen - OPTIONAL11
    if missing:
        raise ValueError(f"rows not found in the generated Table 11: {sorted(missing)}")
    m = re.search(r"c7_tables\.py ([0-9]+\.[0-9]+)", "\n".join(ln for ln in src.splitlines() if ln.startswith("%")))
    gen = m.group(1) if m else "1.1"      # version of the generator, read from the comment block of its body
    head = ("% Table 11 body, one-column layout (R1-C7), written by c7_table_layout.py " + VERSION +
            " from table11_c7-ablation_rows.tex\n"
            "% (c7_tables.py " + gen + "): shorter labels, footnote marks a-d dropped (content in the text of\n"
            "% Sec. 6.2.3), key values in bold; left out: the Conscrypt signature alone, the in-server\n"
            "% signing timer, the TPP sum.\n"
            "% Every value shown is the generated one. n: executions per NIPoK journey. Do not edit by hand.\n")
    return head + "\n".join(out) + "\n"


def parse_time(cell):
    """'9.56 (11.22)' -> ('9.56', '11.22')"""
    m = re.fullmatch(r"([0-9.]+) \(([0-9.]+)\)", cell)
    if not m:
        raise ValueError(f"unexpected time cell in a grouped row: {cell!r}")
    return m.group(1), m.group(2)


def span(values):
    lo = min(values, key=float)
    hi = max(values, key=float)
    return lo if lo == hi else lo + "-" + hi


def summed_counts(counts):
    """['26/26', '20/20', '20/20', '20/20'] -> '86/86' (requests with the expected result / sent)"""
    ok = sum(int(c.split("/")[0]) for c in counts)
    sent = sum(int(c.split("/")[1]) for c in counts)
    return f"{ok}/{sent}"


def group_row(label, members):
    """members: list of (result, count, time) of the generated rows, in GROUPS12 order"""
    results = {r for r, _, _ in members}
    if len(results) != 1:
        raise ValueError(f"members of {label!r} differ in result: {results}")
    med = [parse_time(t)[0] for _, _, t in members]
    p95 = [parse_time(t)[1] for _, _, t in members]
    time = span(med) + " (" + span(p95) + ")"
    return [label, results.pop(), summed_counts([c for _, c, _ in members]), time]


def table12(src):
    out = ["% Table 12 body (R1-C7), written by c7_table_layout.py " + VERSION +
           " from table12_c7-lifecycle_rows.tex (c7_tables.py 1.1):",
           "% key cells in bold; left out: time until the new pod is ready, second login of the 32 users;",
           "% the other five registrations grouped: range of their medians (and of their 95th percentiles) and",
           "% the sum of their counts. Removing \\textbf and expanding the group gives the generated rows. Do not edit by hand."]
    lines = src.splitlines()
    while lines and lines[0].startswith("%"):
        lines.pop(0)
    rows = {}
    for line in lines:   # first pass: cells of every generated row
        m = re.fullmatch(r"\\quad (.*) \\\\", line.strip())
        if m:
            cells = [c.strip() for c in m.group(1).split("&")]
            if len(cells) != 4:
                raise ValueError(f"expected 4 cells: {line!r}")
            rows[cells[0]] = cells
    member_of = {}
    for block, label, members in GROUPS12:
        for t in members:
            if t not in rows:
                raise ValueError(f"group member not in the generated Table 12: {t!r}")
            member_of[t] = block
    for t in DROP12:
        if t not in rows:
            raise ValueError(f"row to leave out not in the generated Table 12: {t!r}")
    emitted = set()
    found = set()
    for line in lines:
        m = re.fullmatch(r"\\quad (.*) \\\\", line.strip())
        if not m:
            out.append(line)
            continue
        cells = [c.strip() for c in m.group(1).split("&")]
        test = cells[0]
        if test in DROP12:
            continue
        if test in member_of:
            block = member_of[test]
            if block not in emitted:
                for b, label, members in GROUPS12:
                    if b == block:
                        g = group_row(label, [rows[t][1:] for t in members])
                        out.append(r"\quad " + " & ".join(g) + r" \\")
                emitted.add(block)
            continue
        for (lab, col) in BOLD12:
            if lab == test:
                cells[col] = r"\textbf{" + cells[col] + "}"
                found.add((lab, col))
        out.append(r"\quad " + " & ".join(cells) + r" \\")
    if found != BOLD12:
        raise ValueError(f"bold cells not found: {sorted(BOLD12 - found)}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--c7", help="benchmark-R1-C7 directory; the generated bodies are read from its analysis/tables")
    ap.add_argument("--tables", help="directory with the generated bodies (overrides --c7)")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--out")
    g.add_argument("--verify")
    a = ap.parse_args()
    if not (a.tables or a.c7):
        ap.error("--tables or --c7 is required")
    tdir = a.tables or os.path.join(a.c7, "analysis", "tables")
    t11 = table11(open(os.path.join(tdir, "table11_c7-ablation_rows.tex"), encoding="utf-8").read())
    t12 = table12(open(os.path.join(tdir, "table12_c7-lifecycle_rows.tex"), encoding="utf-8").read())
    files = {"table11_c7-ablation_onecol_rows.tex": t11, "table12_c7-lifecycle_bold_rows.tex": t12}
    if a.out:
        os.makedirs(a.out, exist_ok=True)
        for name, body in files.items():
            with open(os.path.join(a.out, name), "w", encoding="utf-8") as f:
                f.write(body)
            print(f"wrote {name}")
        return 0
    bad = 0
    for name, body in files.items():
        p = os.path.join(a.verify, name)
        same = os.path.exists(p) and open(p, encoding="utf-8").read() == body
        print(f"{name}: {'= derived from the analysis output' if same else 'DIFFERS'}")
        bad += 0 if same else 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
